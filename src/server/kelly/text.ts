const MIN_STEM_LENGTH = 4;

export function stem(word: string): string {
  let w = word;
  for (const suffix of SUFFIXES) {
    if (w.length - suffix.length >= MIN_STEM_LENGTH && w.endsWith(suffix)) {
      w = w.slice(0, -suffix.length);
      break;
    }
  }
  return w;
}

export function tokenize(text: string | null | undefined): string[] {
  if (!text) return [];
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^\p{L}\p{N}]+/u)
    .filter((t) => t.length >= 2 && !STOP_WORDS.has(t))
    .map(stem);
}

export function termFrequency(tokens: string[]): Map<string, number> {
  const tf = new Map<string, number>();
  for (const token of tokens) tf.set(token, (tf.get(token) ?? 0) + 1);
  return tf;
}

/** Косинусная близость по частотам термов. Корпус мал, IDF не применяется. */
export function cosineSimilarity(a: string[], b: string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const tfA = termFrequency(a);
  const tfB = termFrequency(b);
  let dot = 0;
  for (const [term, countA] of tfA) {
    const countB = tfB.get(term);
    if (countB) dot += countA * countB;
  }
  if (dot === 0) return 0;
  const normA = Math.sqrt([...tfA.values()].reduce((acc, v) => acc + v * v, 0));
  const normB = Math.sqrt([...tfB.values()].reduce((acc, v) => acc + v * v, 0));
  return dot / (normA * normB);
}
